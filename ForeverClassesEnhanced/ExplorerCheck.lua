----------------------------------------------------------------------
-- Total sample-point count (computed once at load)
----------------------------------------------------------------------

local TOTAL_POINTS = 0
for _, zone in ipairs(ZONES) do
    TOTAL_POINTS = TOTAL_POINTS + #zone[3]
end

----------------------------------------------------------------------
-- Core exploration check
----------------------------------------------------------------------

--- Scan all zone sample points and return (exploredCount, totalCount).
--- Uses C_MapExplorationInfo.GetExploredAreaIDsAtPosition().
local function scanExploration()
    if not C_MapExplorationInfo or not C_MapExplorationInfo.GetExploredAreaIDsAtPosition then
        return nil, nil, "C_MapExplorationInfo API not available"
    end
    if not CreateVector2D then
        return nil, nil, "CreateVector2D not available"
    end

    local explored = 0
    local total = TOTAL_POINTS

    for _, zone in ipairs(ZONES) do
        local mapID = zone[1]
        local points = zone[3]
        for _, pt in ipairs(points) do
            local pos = CreateVector2D(pt[1], pt[2])
            local areaIDs = C_MapExplorationInfo.GetExploredAreaIDsAtPosition(mapID, pos)
            if areaIDs and type(areaIDs) == "table" then
                for _ in pairs(areaIDs) do
                    explored = explored + 1
                    break  -- at least one ID = explored
                end
            end
        end
    end

    return explored, total, nil
end

----------------------------------------------------------------------
-- Required exploration % based on player level
----------------------------------------------------------------------

-- Two-phase exponential curve:
--   Phase 1 (lv 1-40): ramps from 0% to 25%   — 25 * (level/40)^1.8
--   Phase 2 (lv 40-60): ramps from 25% to 75%  — 25 + 50 * ((level-40)/20)^1.8
local CURVE_EXP = 1.8

local function requiredPct(level)
    if level >= 60 then return 75 end
    if level <= 1 then return 0 end
    if level <= 40 then
        return 25 * ((level / 40) ^ CURVE_EXP)
    else
        return 25 + 50 * (((level - 40) / 20) ^ CURVE_EXP)
    end
end

----------------------------------------------------------------------
-- Public API
----------------------------------------------------------------------

--- Run the Explorer challenge check.
--- Returns (status, detail) in the same format as other ChallengeCheck rules.
function EC.CheckExplorer()
    local explored, total, err = scanExploration()

    if err then
        return UNCHECKED, err
    end
    if not total or total == 0 then
        return UNCHECKED, "No exploration data available"
    end

    local pct = (explored / total) * 100
    local level = UnitLevel("player") or 1
    local req = requiredPct(level)

    local detail = string.format(
        "%.1f%% explored (%d/%d points) — need %.1f%% at level %d",
        pct, explored, total, req, level
    )

    if pct >= req then
        return PASS, detail
    end
    return FAIL, detail
end

--- Get raw exploration stats (for display in RequirementsPanel tooltip etc.)
function EC.GetStats()
    local explored, total, err = scanExploration()
    if err then return 0, 0, 0, err end
    local level = UnitLevel("player") or 1
    local pct = total > 0 and (explored / total) * 100 or 0
    return pct, requiredPct(level), explored, total
end
